function createIdempotencyKey() {
    if (globalThis.crypto?.randomUUID) return globalThis.crypto.randomUUID();
    return "xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx".replace(/[xy]/g, (character) => {
        const random = Math.floor(Math.random() * 16);
        return (character === "x" ? random : (random & 0x3) | 0x8).toString(16);
    });
}

async function fetchConfig() {
    const response = await fetch("/api/config.json", { headers: { Accept: "application/json" }, cache: "no-store" });
    if (!response.ok) throw new Error("config");
    const config = await response.json();
    if (typeof config.turnstileSiteKey !== "string" || !config.turnstileSiteKey.trim()) throw new Error("config");
    return config.turnstileSiteKey.trim();
}

function loadTurnstileLibrary() {
    if (window.turnstile) return Promise.resolve();
    if (libraryPromise) return libraryPromise;
    libraryPromise = new Promise((resolve, reject) => {
        const script = document.createElement("script");
        script.src = "https://challenges.cloudflare.com/turnstile/v0/api.js?render=explicit";
        script.async = true;
        script.onload = () => window.turnstile ? resolve() : reject(new Error("turnstile"));
        script.onerror = () => reject(new Error("turnstile"));
        document.head.append(script);
    });
    return libraryPromise;
}

async function renderTurnstile() {
    if (widgetId !== undefined) return;
    turnstileArea.hidden = false;
    turnstileStatus.textContent = text("verification");
    const configLoad = configPromise ||= fetchConfig();
    try {
        const [siteKey] = await Promise.all([configLoad, loadTurnstileLibrary()]);
        widgetId = window.turnstile.render(turnstileWidget, {
            sitekey: siteKey,
            action: "feedback",
            theme: "light",
            language: "auto",
            callback: (value) => {
                turnstileToken = value;
                turnstileStatus.textContent = "";
                if (tokenWaiter) { tokenWaiter.resolve(value); tokenWaiter = undefined; }
            },
            "expired-callback": () => { turnstileToken = ""; },
            "error-callback": () => {
                turnstileToken = "";
                if (tokenWaiter) { tokenWaiter.reject(new Error("turnstile")); tokenWaiter = undefined; }
            }
        });
    } catch (error) {
        if (configPromise === configLoad) configPromise = undefined;
        if (!window.turnstile) libraryPromise = undefined;
        throw error;
    }
}

async function getTurnstileToken() {
    if (turnstileToken) return turnstileToken;
    await renderTurnstile();
    if (turnstileToken) return turnstileToken;
    return new Promise((resolve, reject) => {
        const timeoutId = window.setTimeout(() => {
            if (tokenWaiter?.resolve === resolveToken) tokenWaiter = undefined;
            reject(new Error("turnstile"));
        }, TURNSTILE_WAIT_MS);
        const resolveToken = (value) => {
            window.clearTimeout(timeoutId);
            resolve(value);
        };
        const rejectToken = (error) => {
            window.clearTimeout(timeoutId);
            reject(error);
        };
        tokenWaiter = { resolve: resolveToken, reject: rejectToken };
    });
}

function discardTurnstileToken() {
    turnstileToken = "";
    if (widgetId !== undefined && window.turnstile) window.turnstile.reset(widgetId);
}

function feedbackPayload(token) {
    const payload = {
        type: form.elements.feedbackType.value,
        message: message.value.trim(),
        turnstileToken: token,
        uiLocale: locale
    };
    const contact = form.elements.contact.value.trim();
    if (contact) payload.contact = contact;
    if (metadata.appVersion) payload.appVersion = metadata.appVersion;
    if (metadata.androidVersion) payload.androidVersion = metadata.androidVersion;
    return payload;
}

async function submitFeedback(token) {
    const response = await fetch("/api/feedback", {
        method: "POST",
        headers: { "Content-Type": "application/json", Accept: "application/json", "Idempotency-Key": submissionKey },
        body: JSON.stringify(feedbackPayload(token))
    });
    let result;
    try { result = await response.json(); } catch { result = null; }
    if (response.ok && result?.ok !== false) return;
    if (response.status === 429 || result?.error?.code === "rate_limited") throw new Error("rate-limit");
    if (String(result?.error?.code || "").includes("turnstile")) throw new Error("turnstile");
    throw new Error("server");
}

message.addEventListener("input", () => {
    updateCounter();
    if (message.getAttribute("aria-invalid") === "true") validateMessage();
});

languagePicker.addEventListener("change", () => setLocale(languagePicker.value, true));

form.addEventListener("submit", async (event) => {
    event.preventDefault();
    clearSubmitError();
    if (!validateMessage()) { message.focus(); return; }
    setBusy(true);
    try {
        const token = await getTurnstileToken();
        await submitFeedback(token);
        form.hidden = true;
        successState.hidden = false;
        submissionKey = createIdempotencyKey();
        successState.querySelector("h2").focus();
    } catch (error) {
        discardTurnstileToken();
        showSubmitError(error.message === "rate-limit" ? text("rateLimitError") : error.message === "server" ? text("serverError") : error.message === "config" || error.message === "turnstile" ? text("verificationFailed") : text("networkError"));
    } finally {
        setBusy(false);
    }
});

resetButton.addEventListener("click", () => {
    form.reset();
    message.removeAttribute("aria-invalid");
    messageError.hidden = true;
    clearSubmitError();
    discardTurnstileToken();
    updateCounter();
    successState.hidden = true;
    form.hidden = false;
    message.focus();
});

